classdef MultiProtocolDissector
    % ScapyML.MultiProtocolDissector - Generate Wireshark dissector for multiple protocols
    %
    % Uses message ID-based protocol discrimination for proper multi-protocol support
    
    methods (Static)
        function generate(protoNames, outFile, udpPort, enumDefs, discConfig)
            % Generate multi-protocol Wireshark dissector with message ID discrimination
            %
            % Args:
            %   protoNames - Cell array of protocol names
            %   outFile    - Output .lua file path
            %   udpPort    - UDP port to register (optional)
            %   enumDefs   - Cell array of EnumDef objects (optional)
            %   discConfig - DiscriminatorConfig object (optional, will prompt if not provided)
            
            if nargin < 3, udpPort = []; end
            if nargin < 4, enumDefs = {}; end
            if nargin < 5 || isempty(discConfig)
                % Prompt user to configure discriminator
                fprintf('\n');
                fprintf('Multi-protocol dissector requires message ID discrimination.\n');
                fprintf('Opening configuration dialog...\n\n');
                discConfig = ScapyML.DiscriminatorConfig.fromGUI(protoNames);
                
                if isempty(discConfig)
                    fprintf('Discriminator configuration cancelled.\n');
                    return;
                end
            end
            
            % Validate discriminator configuration
            if ~discConfig.validateUniqueness()
                error('Discriminator configuration has duplicate values!');
            end
            
            % Convert enums to map for quick lookup
            enumMap = containers.Map();
            if ~isempty(enumDefs)
                for i = 1:numel(enumDefs)
                    enumMap(enumDefs{i}.Name) = enumDefs{i};
                end
            end
            
            if ~iscell(protoNames)
                protoNames = {protoNames};
            end
            
            if isempty(protoNames)
                error('Must specify at least one protocol');
            end
            
            fprintf('[MultiProtocolDissector] Generating dissector for %d protocols\n', ...
                numel(protoNames));
            
            % Get protocol registry
            reg = ScapyML.ProtocolRegistry.instance();
            
            % Get all protocols and show discriminator info
            protos = cell(1, numel(protoNames));
            for i = 1:numel(protoNames)
                try
                    protos{i} = reg.get(protoNames{i});
                    [fieldName, offset, size] = discConfig.getProtocolConfig(protoNames{i});
                    value = discConfig.getProtocolValue(protoNames{i});
                    fprintf('  - %s: field=%s, offset=%d, size=%d, value=0x%X (%d bytes)\n', ...
                        protoNames{i}, fieldName, offset, size, value, protos{i}.totalBytes());
                catch ME
                    error('Protocol configuration error for %s: %s', protoNames{i}, ME.message);
                end
            end
            
            % Generate combined dissector
            lines = {};
            
            % Header
            lines{end+1} = '-- Auto-generated by ScapyML MultiProtocolDissector';
            lines{end+1} = sprintf('-- Protocols: %s', strjoin(protoNames, ', '));
            lines{end+1} = sprintf('-- Generated: %s', datestr(now));
            lines{end+1} = '-- Message ID-based protocol discrimination';
            lines{end+1} = '';
            
            % Create main protocol
            mainName = 'scapyml_multi';
            lines{end+1} = sprintf('local %s_proto = Proto("%s", "ScapyML Multi-Protocol")', ...
                mainName, mainName);
            lines{end+1} = '';
            
            % ProtoField declarations for all protocols
            lines{end+1} = '-- ProtoField definitions';
            lines{end+1} = 'local f = {}';
            lines{end+1} = '';
            
            % Collect all fields from all protocols
            allFields = {};
            protoFieldMap = containers.Map();  % proto name -> field list
            
            for i = 1:numel(protos)
                p = protos{i};
                fields = ScapyML.WiresharkDissector.collectFields(p.Fields);
                allFields = [allFields, fields]; %#ok<AGROW>
                protoFieldMap(protoNames{i}) = fields;
            end
            
            % Declare all fields (with unique names to avoid collisions)
            fieldCounter = containers.Map();  % Track field names
            
            for j = 1:numel(protoNames)
                protoName = protoNames{j};
                fields = protoFieldMap(protoName);
                
                for i = 1:numel(fields)
                    fd = fields{i};
                    luaType = ScapyML.WiresharkDissector.luaFieldType(fd);
                    
                    % Create unique Lua variable name: protoname_fieldname
                    uniqueFieldName = sprintf('%s_%s', lower(protoName), fd.Name);
                    
                    % Create field abbreviation for Wireshark
                    fieldAbbr = sprintf('%s.%s.%s', mainName, lower(protoName), lower(fd.Name));
                    
                    descr = fd.Name;
                    
                    lines{end+1} = sprintf('f.%s = ProtoField.%s("%s", "%s")', ...
                        uniqueFieldName, luaType, fieldAbbr, descr);
                    
                    % Store for later use
                    if ~fieldCounter.isKey(protoName)
                        fieldCounter(protoName) = {};
                    end
                    temp = fieldCounter(protoName);
                    temp{end+1} = uniqueFieldName;
                    fieldCounter(protoName) = temp;
                end
            end
            
            % Collect all unique field names for fields table
            allFieldNames = {};
            for j = 1:numel(protoNames)
                if fieldCounter.isKey(protoNames{j})
                    allFieldNames = [allFieldNames, fieldCounter(protoNames{j})];
                end
            end
            
            lines{end+1} = '';
            lines{end+1} = sprintf('%s_proto.fields = {', mainName);
            for i = 1:numel(allFieldNames)
                if i < numel(allFieldNames)
                    lines{end+1} = sprintf('  f.%s,', allFieldNames{i});
                else
                    lines{end+1} = sprintf('  f.%s', allFieldNames{i});
                end
            end
            lines{end+1} = '}';
            lines{end+1} = '';
            
            % Individual dissector functions for each protocol
            for i = 1:numel(protos)
                p = protos{i};
                pname = protoNames{i};
                funcName = sprintf('dissect_%s', lower(pname));
                
                lines{end+1} = sprintf('-- Dissector for %s', pname);
                lines{end+1} = sprintf('function %s(buffer, pinfo, tree)', funcName);
                lines{end+1} = sprintf('  local subtree = tree:add(%s_proto, buffer(), "%s")', mainName, pname);
                lines{end+1} = sprintf('  pinfo.cols.info = "%s"', pname);
                lines{end+1} = '';
                
                % Add fields for this protocol (with renamed field references)
                [fieldLines, ~] = ScapyML.WiresharkDissector.emitFieldList( ...
                    {}, p.Fields, 0, p.IsUnion, '  ');
                
                % Replace field references with unique names
                for j = 1:numel(fieldLines)
                    line = fieldLines{j};
                    % Replace "f.fieldname" with "f.protoname_fieldname"
                    line = regexprep(line, 'f\.(\w+)', sprintf('f.%s_$1', lower(pname)));
                    lines{end+1} = line;
                end
                
                lines{end+1} = 'end';
                lines{end+1} = '';
            end
            
            % Main dissector function with message ID discrimination
            lines{end+1} = sprintf('function %s_proto.dissector(buffer, pinfo, tree)', mainName);
            lines{end+1} = sprintf('  local buflen = buffer:len()');
            lines{end+1} = sprintf('  pinfo.cols.protocol = "%s"', upper(mainName));
            lines{end+1} = '';
            
            % Group protocols by discriminator location
            locationGroups = ScapyML.MultiProtocolDissector.groupByDiscriminator(protoNames, discConfig);
            
            % Generate discrimination logic for each group
            firstGroup = true;
            locationKeys = locationGroups.keys();
            
            for g = 1:numel(locationKeys)
                locKey = locationKeys{g};
                group = locationGroups(locKey);
                
                offset = group.offset;
                size = group.size;
                protocols = group.protocols;
                
                % Check buffer length for this discriminator
                minLen = offset + size;
                
                if firstGroup
                    lines{end+1} = sprintf('  -- Check buffer length for discriminator at offset %d', offset);
                    lines{end+1} = sprintf('  if buflen < %d then', minLen);
                    firstGroup = false;
                else
                    lines{end+1} = sprintf('  elseif buflen < %d then', minLen);
                end
                
                lines{end+1} = '    tree:add_proto_expert_info(ef_too_short)';
                lines{end+1} = sprintf('    pinfo.cols.info = "Packet too short (" .. buflen .. " bytes)"');
                lines{end+1} = '    return 0';
                
                % Read discriminator value
                lines{end+1} = sprintf('  else');
                lines{end+1} = sprintf('    -- Read discriminator at offset %d (size %d)', offset, size);
                
                if size == 1
                    lines{end+1} = sprintf('    local disc_value = buffer(%d, 1):uint()', offset);
                elseif size == 2
                    lines{end+1} = sprintf('    local disc_value = buffer(%d, 2):uint()', offset);
                elseif size == 4
                    lines{end+1} = sprintf('    local disc_value = buffer(%d, 4):uint()', offset);
                end
                
                lines{end+1} = '';
                
                % Switch on discriminator value
                lines{end+1} = '    -- Dispatch based on message ID';
                for p = 1:numel(protocols)
                    protoName = protocols{p}.name;
                    value = protocols{p}.value;
                    funcName = sprintf('dissect_%s', lower(protoName));
                    
                    if p == 1
                        lines{end+1} = sprintf('    if disc_value == 0x%X then', value);
                    else
                        lines{end+1} = sprintf('    elseif disc_value == 0x%X then', value);
                    end
                    
                    lines{end+1} = sprintf('      pinfo.cols.protocol = "%s"', upper(protoName));
                    lines{end+1} = sprintf('      %s(buffer, pinfo, tree)', funcName);
                    lines{end+1} = sprintf('      return buflen');
                end
                
                % Unknown message ID
                lines{end+1} = '    else';
                lines{end+1} = '      tree:add_proto_expert_info(ef_unknown_msgid)';
                lines{end+1} = '      pinfo.cols.info = string.format("Unknown Message ID: 0x%02X", disc_value)';
                lines{end+1} = '      return 0';
                lines{end+1} = '    end';
            end
            
            lines{end+1} = '  end';
            lines{end+1} = 'end';
            lines{end+1} = '';
            
            % Expert info definitions
            lines{end+1} = '-- Expert info';
            lines{end+1} = 'local ef_too_short = ProtoExpert.new("scapyml.too_short", "Packet too short for discriminator",';
            lines{end+1} = '                                      expert.group.MALFORMED, expert.severity.ERROR)';
            lines{end+1} = 'local ef_unknown_msgid = ProtoExpert.new("scapyml.unknown_msgid", "Unknown message ID",';
            lines{end+1} = '                                         expert.group.PROTOCOL, expert.severity.WARN)';
            lines{end+1} = sprintf('%s_proto.experts = { ef_too_short, ef_unknown_msgid }', mainName);
            lines{end+1} = '';
            
            % Register
            if ~isempty(udpPort)
                lines{end+1} = sprintf('-- Register on UDP port %d', udpPort);
                lines{end+1} = 'local udp_table = DissectorTable.get("udp.port")';
                lines{end+1} = sprintf('udp_table:add(%d, %s_proto)', udpPort, mainName);
            else
                lines{end+1} = '-- To register: DissectorTable.get("udp.port"):add(<PORT>, scapyml_multi_proto)';
            end
            
            % Write file — binary mode, strip non-ASCII to prevent NBSP/smart-quote artefacts
            fid = fopen(outFile, 'wb');
            if fid < 0
                error('Cannot write file: %s', outFile);
            end
            for i = 1:numel(lines)
                line = char(lines{i});  % ensure char, never cell/string object
                line = line(arrayfun(@(c) (c >= 32 && c <= 126) || c == 9, line));
                fprintf(fid, '%s\n', line);
            end
            fclose(fid);
            
            fprintf('[MultiProtocolDissector] Written to: %s\n', outFile);
            fprintf('  Total protocols: %d\n', numel(protoNames));
            fprintf('  Discrimination: Message ID-based\n');
        end
        
        function locationGroups = groupByDiscriminator(protoNames, discConfig)
            % Group protocols by discriminator field location
            locationGroups = containers.Map();
            
            for i = 1:numel(protoNames)
                protoName = protoNames{i};
                [fieldName, offset, size] = discConfig.getProtocolConfig(protoName);
                value = discConfig.getProtocolValue(protoName);
                
                % Create unique key for this discriminator location
                locKey = sprintf('%s_%d_%d', fieldName, offset, size);
                
                if ~locationGroups.isKey(locKey)
                    group = struct();
                    group.fieldName = fieldName;
                    group.offset = offset;
                    group.size = size;
                    group.protocols = {};
                    locationGroups(locKey) = group;
                end
                
                % Add protocol to this location group
                group = locationGroups(locKey);
                group.protocols{end+1} = struct('name', protoName, 'value', value);
                locationGroups(locKey) = group;
            end
        end
    end
end
