classdef WiresharkDissector
% ScapyML.WiresharkDissector  Generate Wireshark Lua dissector scripts.
%
% Handles:
%   - All primitive types (integers, bit-fields, float, double)
%   - Big-endian and little-endian per field
%   - Nested structs (ProtocolDef children in the field tree)
%   - Unions: all member fields shown at the same byte offset
%
% Correct Lua syntax for adding fields to a subtree:
%   subtree:add(f.fieldname, buffer(byteOffset, byteLen))       -- big-endian
%   subtree:add_le(f.fieldname, buffer(byteOffset, byteLen))    -- little-endian
%
% Usage:
%   ScapyML.WiresharkDissector.generate(protoDef, 'my_proto.lua');
%   ScapyML.WiresharkDissector.generate(protoDef, 'my_proto.lua', 1234);

    methods (Static)

        function generate(protoDef, outFile, udpPort, enumDefs)
            if nargin < 3, udpPort = []; end
            if nargin < 4, enumDefs = {}; end

            lines = {};
            p      = protoDef;
            pname  = char(lower(p.Name));   % force char, lowercase Lua identifier
            pdesc  = char(p.Name);          % force char, display name
            
            % Convert enums to map for quick lookup
            enumMap = containers.Map();
            if ~isempty(enumDefs)
                for i = 1:numel(enumDefs)
                    enumMap(enumDefs{i}.Name) = enumDefs{i};
                end
            end

            % ---- Header ----
            lines{end+1} = '-- Auto-generated by ScapyML WiresharkDissector';
            lines{end+1} = sprintf('-- Protocol : %s', pdesc);
            lines{end+1} = sprintf('-- Generated: %s', datestr(now));
            lines{end+1} = sprintf('-- Total size: %d bytes', p.totalBytes());
            lines{end+1} = '';
            lines{end+1} = sprintf('local %s_proto = Proto("%s", "%s Protocol")', ...
                pname, pname, pdesc);
            lines{end+1} = '';

            % ---- ProtoField declarations ----
            % collectFieldsWithMeta returns structs with:
            %   .fd          - FieldDef object
            %   .luaKey      - unique Lua variable name  e.g. "structname_var1"
            %   .filterAbbr  - Wireshark filter path     e.g. "structname.substruct.var1"
            %   .displayName - bare field name shown in tree  e.g. "var1"
            lines{end+1} = sprintf('-- ProtoField definitions');
            lines{end+1} = 'local f = {}';
            lines{end+1} = '';

            allMeta = ScapyML.WiresharkDissector.collectFieldsWithMeta(p.Fields, pname, 0, p.IsUnion);
            for k = 1:numel(allMeta)
                m       = allMeta{k};
                fd      = m.fd;
                luaKey  = m.luaKey;
                abbr    = m.filterAbbr;
                descr   = m.displayName;
                luaType = ScapyML.WiresharkDissector.luaFieldType(fd);

                % Check if this field's CType is a known enum (exact match)
                enumDef = [];
                if ~isempty(enumMap) && enumMap.isKey(fd.CType)
                    enumDef = enumMap(fd.CType);
                end

                if ~isempty(enumDef)
                    lines{end+1} = sprintf('local %s_vals = {', luaKey);
                    enumNames = enumDef.allNames();
                    for ei = 1:numel(enumNames)
                        ename  = enumNames{ei};
                        evalue = enumDef.getValue(ename);
                        lines{end+1} = sprintf('  [%d] = "%s",', evalue, ename);
                    end
                    lines{end+1} = '}';
                    % Enum value tables are always keyed by decimal value —
                    % base.DEC is correct regardless of whether the field
                    % is also a bit-field. The bit-field's mask (if any)
                    % still displays in hex on its own, independent of base.
                    if m.isBitField
                        lines{end+1} = sprintf('f.%s = ProtoField.%s("%s", "%s", base.DEC, %s_vals, 0x%X)', ...
                            luaKey, luaType, abbr, descr, luaKey, m.bfMask);
                    else
                        lines{end+1} = sprintf('f.%s = ProtoField.%s("%s", "%s", base.DEC, %s_vals)', ...
                            luaKey, luaType, abbr, descr, luaKey);
                    end
                else
                    if m.isBitField
                        lines{end+1} = sprintf('f.%s = ProtoField.%s("%s", "%s", base.HEX, nil, 0x%X)', ...
                            luaKey, luaType, abbr, descr, m.bfMask);
                    else
                        lines{end+1} = sprintf('f.%s = ProtoField.%s("%s", "%s")', ...
                            luaKey, luaType, abbr, descr);
                    end
                end
            end

            lines{end+1} = '';
            lines{end+1} = sprintf('%s_proto.fields = {', pname);
            for k = 1:numel(allMeta)
                if k < numel(allMeta)
                    lines{end+1} = sprintf('  f.%s,', allMeta{k}.luaKey);
                else
                    lines{end+1} = sprintf('  f.%s', allMeta{k}.luaKey);
                end
            end
            lines{end+1} = '}';
            lines{end+1} = '';

            % ---- Dissector function ----
            lines{end+1} = sprintf('function %s_proto.dissector(buffer, pinfo, tree)', pname);
            lines{end+1} = sprintf('  pinfo.cols.protocol = "%s"', upper(pname));
            lines{end+1} = sprintf('  local subtree = tree:add(%s_proto, buffer(), "%s")', pname, pdesc);
            lines{end+1} = '';

            % Emit field accesses — luaKey is fd.Name (already unique from HeaderParser)
            lines = ScapyML.WiresharkDissector.emitFieldList(lines, p.Fields, 0, p.IsUnion, '  ', 'subtree', '');

            lines{end+1} = 'end';
            lines{end+1} = '';

            % ---- UDP registration ----
            if ~isempty(udpPort)
                lines{end+1} = '-- Register on UDP port';
                lines{end+1} = 'local udp_table = DissectorTable.get("udp.port")';
                lines{end+1} = sprintf('udp_table:add(%d, %s_proto)', udpPort, pname);
            else
                lines{end+1} = sprintf('-- To register: DissectorTable.get("udp.port"):add(<PORT>, %s_proto)', pname);
            end

            % ---- Write file ----
            % Open in binary mode so line endings are exactly what we write.
            % Strip any non-ASCII characters (NBSP, smart quotes, etc.) that
            % may have come from protocol/enum names in the source header.
            fid = fopen(outFile, 'wb');
            if fid < 0
                error('ScapyML:WiresharkDissector:WriteError', ...
                    'Cannot write file: %s', outFile);
            end
            for k = 1:numel(lines)
                line = char(lines{k});  % ensure char, never cell/string object
                % Keep only printable ASCII (0x20-0x7E) plus tab (0x09)
                line = line(arrayfun(@(c) (c >= 32 && c <= 126) || c == 9, line));
                fprintf(fid, '%s\n', line);
            end
            fclose(fid);

            fprintf('[ScapyML] Wireshark dissector written to: %s\n', outFile);
        end

        % ----------------------------------------------------------------
        % Recursively emit Lua field-access lines for a list of fields.
        % bitOffset: running bit position in the packet.
        % isUnion:   when true all children start at startBit (not bitOffset).
        % indent:    leading whitespace string.
        % subtreeName: name of current subtree variable (for nested structures)
        % Returns updated lines cell and the new bitOffset.
        % ----------------------------------------------------------------
        function [lines, bitOffset] = emitFieldList(lines, fields, bitOffset, isUnion, indent, subtreeName, luaKeyPrefix)
            if nargin < 6, subtreeName  = 'subtree'; end
            if nargin < 7, luaKeyPrefix = '';        end

            startBit = bitOffset;

            for k = 1:numel(fields)
                f = fields{k};

                if isa(f, 'ScapyML.ProtocolDef')
                    if isUnion
                        childStart = startBit;
                    else
                        % Align nested struct/union start position (v2.3.1, KI-001)
                        alignBits = ScapyML.ProtocolDef.structAlignBits(f);
                        bitOffset = ScapyML.ProtocolDef.alignBitPos(bitOffset, alignBits);
                        childStart = bitOffset;
                    end

                    nestedBytes       = ceil(f.TotalBits / 8);
                    nestedByteOffset  = floor(childStart / 8);
                    nestedSubtreeName = sprintf('subtree_%s', f.Name);

                    if f.IsUnion
                        lines{end+1} = sprintf('%slocal %s = %s:add(buffer(%d, %d), "%s (union)")', ...
                            indent, nestedSubtreeName, subtreeName, nestedByteOffset, nestedBytes, f.Name);
                    else
                        lines{end+1} = sprintf('%slocal %s = %s:add(buffer(%d, %d), "%s")', ...
                            indent, nestedSubtreeName, subtreeName, nestedByteOffset, nestedBytes, f.Name);
                    end

                    [lines, ~] = ScapyML.WiresharkDissector.emitFieldList( ...
                        lines, f.Fields, childStart, f.IsUnion, [indent, '  '], nestedSubtreeName, '');

                    if ~isUnion
                        bitOffset = bitOffset + f.TotalBits;
                    end

                elseif isa(f, 'ScapyML.FieldDef')
                    if isUnion
                        fieldBit = startBit;
                    else
                        % Align field start position, except bit-fields
                        % which pack with no inter-field padding (v2.3.1, KI-001)
                        if ~f.IsBitField
                            alignBits = ScapyML.ProtocolDef.fieldAlignBytes(f) * 8;
                            bitOffset = ScapyML.ProtocolDef.alignBitPos(bitOffset, alignBits);
                        end
                        fieldBit = bitOffset;
                    end

                    luaKey = sprintf('%s%s', luaKeyPrefix, f.Name);
                    [lines, fBits] = ScapyML.WiresharkDissector.emitOneField( ...
                        lines, f, fieldBit, indent, subtreeName, luaKey);

                    if ~isUnion
                        bitOffset = fieldBit + fBits;
                    end
                end
            end
        end

        % ----------------------------------------------------------------
        % Emit a single field access line.
        % Returns updated lines and the number of bits this field occupies.
        % ----------------------------------------------------------------
        function [lines, bits] = emitOneField(lines, fd, bitOffset, indent, subtreeName, luaKey)
            if nargin < 5, subtreeName = 'subtree'; end
            if nargin < 6, luaKey = fd.Name;        end  % fallback: use raw field name

            byteOff  = floor(bitOffset / 8);
            isFloat  = strcmp(fd.CType, 'float');
            isDouble = strcmp(fd.CType, 'double');

            if fd.IsArray
                arraySize  = fd.ArraySize;

                if fd.IsBitField,   elemBits = fd.BitSize;
                elseif isFloat,     elemBits = 32;
                elseif isDouble,    elemBits = 64;
                else,               elemBits = fd.ByteSize * 8;
                end

                bits       = elemBits * arraySize;
                totalBytes = ceil(bits / 8);

                lines{end+1} = sprintf('%sdo', indent);
                % Group node: use label-only subtree (no ProtoField) to avoid
                % size mismatch — f.xxx is declared for one element, not the whole array
                lines{end+1} = sprintf('%s  local array_tree = %s:add(buffer(%d, %d), "%s[%d]")', ...
                    indent, subtreeName, byteOff, totalBytes, fd.Name, arraySize);

                currentBitOffset = bitOffset;
                for i = 1:arraySize
                    elemByteOff = floor(currentBitOffset / 8);
                    if fd.IsBitField
                        nbytes = ceil((mod(currentBitOffset, 8) + elemBits) / 8);
                        addM   = ScapyML.WiresharkDissector.addMethod(fd.Endian, nbytes);
                        lines{end+1} = sprintf('%s  array_tree:%s(f.%s, buffer(%d, %d))', ...
                            indent, addM, luaKey, elemByteOff, nbytes);
                    else
                        if isFloat || isDouble
                            elemBytes = elemBits / 8;
                            addM = ScapyML.WiresharkDissector.addMethod(fd.Endian);
                        else
                            elemBytes = fd.ByteSize;
                            addM = ScapyML.WiresharkDissector.addMethod(fd.Endian, elemBytes);
                        end
                        lines{end+1} = sprintf('%s  array_tree:%s(f.%s, buffer(%d, %d))', ...
                            indent, addM, luaKey, elemByteOff, elemBytes);
                    end
                    currentBitOffset = currentBitOffset + elemBits;
                end
                lines{end+1} = sprintf('%send', indent);

            elseif fd.IsBitField
                bits   = fd.BitSize;
                nbytes = ceil((mod(bitOffset, 8) + bits) / 8);
                addM   = ScapyML.WiresharkDissector.addMethod(fd.Endian, nbytes);
                lines{end+1} = sprintf('%s%s:%s(f.%s, buffer(%d, %d))', ...
                    indent, subtreeName, addM, luaKey, byteOff, nbytes);

            elseif isFloat
                bits  = 32; nbytes = 4;
                addM  = ScapyML.WiresharkDissector.addMethod(fd.Endian);
                lines{end+1} = sprintf('%s%s:%s(f.%s, buffer(%d, %d))', indent, subtreeName, addM, luaKey, byteOff, nbytes);

            elseif isDouble
                bits  = 64; nbytes = 8;
                addM  = ScapyML.WiresharkDissector.addMethod(fd.Endian);
                lines{end+1} = sprintf('%s%s:%s(f.%s, buffer(%d, %d))', indent, subtreeName, addM, luaKey, byteOff, nbytes);

            else
                nbytes = fd.ByteSize; bits = nbytes * 8;
                addM   = ScapyML.WiresharkDissector.addMethod(fd.Endian, nbytes);
                lines{end+1} = sprintf('%s%s:%s(f.%s, buffer(%d, %d))', indent, subtreeName, addM, luaKey, byteOff, nbytes);
            end
        end

        % ----------------------------------------------------------------
        % Depth-first collect all FieldDef objects with naming metadata.
        %
        % FieldDef.Name already contains the full unique path as built by
        % HeaderParser (e.g. "SubStruct_Sync" for a nested field).
        % We use it directly as the Lua variable key.
        %
        % For bitfields, also computes:
        %   .isBitField  - true
        %   .bfNbytes    - number of container bytes needed
        %   .bfMask      - bitmask positioned within the container (for ProtoField)
        % ----------------------------------------------------------------
        function [meta, bitOffset] = collectFieldsWithMeta(fieldList, pname, bitOffset, isUnion)
            % isUnion: true when fieldList belongs to a union, so every member
            % starts at the same bit position (keeps the bit-field masks
            % consistent with emitFieldList, which also overlaps union members).
            if nargin < 3, bitOffset = 0; end
            if nargin < 4, isUnion = false; end
            unionStart = bitOffset;
            meta = {};
            for k = 1:numel(fieldList)
                f = fieldList{k};
                if isUnion
                    bitOffset = unionStart;
                end
                if isa(f, 'ScapyML.FieldDef')
                    if f.IsBitField
                        % Bit-fields pack with no inter-field padding —
                        % no alignment applied (v2.3.1, KI-001 consistency)
                        bits         = f.BitSize;
                        nbytes       = ceil((mod(bitOffset, 8) + bits) / 8);
                        shift        = nbytes*8 - mod(bitOffset, 8) - bits;
                        rawMask      = bitand(2^bits - 1, 2^32 - 1);
                        m.bfNbytes   = nbytes;
                        m.bfMask     = bitand(bitshift(rawMask, shift), 2^(nbytes*8) - 1);
                        bitOffset    = bitOffset + bits;
                    elseif f.IsArray
                        alignBits = ScapyML.ProtocolDef.fieldAlignBytes(f) * 8;
                        bitOffset = ScapyML.ProtocolDef.alignBitPos(bitOffset, alignBits);
                        bitOffset = bitOffset + f.ByteSize * 8 * f.ArraySize;
                    else
                        alignBits = ScapyML.ProtocolDef.fieldAlignBytes(f) * 8;
                        bitOffset = ScapyML.ProtocolDef.alignBitPos(bitOffset, alignBits);
                        bitOffset = bitOffset + f.ByteSize * 8;
                    end
                    m.fd          = f;
                    m.luaKey      = f.Name;
                    m.filterAbbr  = sprintf('%s.%s', pname, lower(f.Name));
                    m.displayName = f.Name;
                    m.isBitField  = f.IsBitField;
                    meta{end+1} = m; %#ok<AGROW>
                elseif isa(f, 'ScapyML.ProtocolDef')
                    alignBits = ScapyML.ProtocolDef.structAlignBits(f);
                    bitOffset = ScapyML.ProtocolDef.alignBitPos(bitOffset, alignBits);
                    startBit = bitOffset;
                    [sub, childOffset] = ScapyML.WiresharkDissector.collectFieldsWithMeta( ...
                        f.Fields, pname, bitOffset, f.IsUnion);
                    meta = [meta, sub]; %#ok<AGROW>
                    if f.IsUnion
                        bitOffset = startBit + f.TotalBits;
                    else
                        bitOffset = childOffset;
                    end
                end
            end
        end

        % ----------------------------------------------------------------
        % Depth-first collect all FieldDef objects (used externally).
        % ----------------------------------------------------------------
        function fields = collectFields(fieldList)
            fields = {};
            for k = 1:numel(fieldList)
                f = fieldList{k};
                if isa(f, 'ScapyML.FieldDef')
                    fields{end+1} = f; %#ok<AGROW>
                elseif isa(f, 'ScapyML.ProtocolDef')
                    sub = ScapyML.WiresharkDissector.collectFields(f.Fields);
                    fields = [fields, sub]; %#ok<AGROW>
                end
            end
        end

        % ----------------------------------------------------------------
        % Helpers
        % ----------------------------------------------------------------

        function method = addMethod(endian, nbytes)
            % Return 'add' (big-endian or single byte) or 'add_le' (little-endian multi-byte).
            if nargin < 2, nbytes = 2; end
            if strcmp(endian, 'little') && nbytes > 1
                method = 'add_le';
            else
                method = 'add';
            end
        end

        function t = luaFieldType(fd)
            if strcmp(fd.CType, 'float'),  t = 'float';  return; end
            if strcmp(fd.CType, 'double'), t = 'double'; return; end

            % Determine if signed: int8_t, int16_t, int32_t, int64_t,
            % int, short, long, signed char, etc.
            ctype = lower(fd.CType);
            isSigned = (~contains(fd.CType, 'uint') && contains(fd.CType, 'int')) || ...
                       contains(ctype, 'short') || contains(ctype, 'long') || ...
                       strcmp(ctype, 'signed') || startsWith(ctype, 'signed ') || ...
                       startsWith(ctype, 's8') || startsWith(ctype, 's16') || ...
                       startsWith(ctype, 's32') || startsWith(ctype, 's64') || ...
                       startsWith(ctype, 'sint');

            if isSigned
                switch fd.ByteSize
                    case 1,  t = 'int8';
                    case 2,  t = 'int16';
                    case 4,  t = 'int32';
                    case 8,  t = 'int64';
                    otherwise, t = 'bytes';
                end
            else
                switch fd.ByteSize
                    case 1,  t = 'uint8';
                    case 2,  t = 'uint16';
                    case 4,  t = 'uint32';
                    case 8,  t = 'uint64';
                    otherwise, t = 'bytes';
                end
            end
        end


        function [lines, bits] = emitOneBitField(lines, fd, bitOffset, indent, treeName)
            % Emit a single bit-field to a specific tree (for grouping)
            %
            % treeName: name of the tree variable (e.g., 'subtree' or 'bitfield_tree')
            
            if nargin < 5, treeName = 'subtree'; end
            
            bits = fd.BitSize;
            byteOff = floor(bitOffset / 8);
            nbytes = ceil((mod(bitOffset, 8) + bits) / 8);
            shift  = nbytes*8 - mod(bitOffset, 8) - bits;
            mask   = bitand(2^bits - 1, 2^32 - 1);
            
            lines{end+1} = sprintf('%sdo', indent);
            lines{end+1} = sprintf('%s  local raw = buffer(%d, %d):uint()', indent, byteOff, nbytes);
            lines{end+1} = sprintf('%s  local val = bit.band(bit.rshift(raw, %d), 0x%X)', indent, shift, mask);
            lines{end+1} = sprintf('%s  %s:add(f.%s, buffer(%d, %d), val)', indent, treeName, fd.Name, byteOff, nbytes);
            lines{end+1} = sprintf('%send', indent);
        end
    end
end
